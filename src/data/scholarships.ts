/**
 * Seed catalog.
 *
 * These entries are illustrative examples with plausible award sizes, deadlines
 * and requirements — they are NOT scraped listings and should not be treated as
 * live program data. The catalog exists so the matching, comparison and planning
 * engines have realistic input out of the box; students add real programs via
 * "Capture from this page" or the manual add form, and those are stored
 * alongside these under `customScholarships`.
 *
 * Every entry is `recurring`, so a past date rolls forward to the next cycle and
 * the catalog never looks stale.
 */

import type {
  ApplicationRequirements,
  EligibilityRule,
  Scholarship,
  ScholarshipCategory,
} from '../core/types';

function requirements(overrides: Partial<ApplicationRequirements> = {}): ApplicationRequirements {
  return {
    essayCount: 0,
    essayWordCounts: [],
    essayTopics: [],
    recommendationLetters: 0,
    transcriptRequired: false,
    fafsaRequired: false,
    portfolioRequired: false,
    interviewRequired: false,
    videoRequired: false,
    otherRequirements: [],
    ...overrides,
  };
}

const RULES = {
  gpa: (min: number, weight: EligibilityRule['weight'] = 'required'): EligibilityRule => ({
    id: `gpa-${min}`,
    field: 'academics.gpa',
    operator: 'gte',
    value: min,
    label: `${min.toFixed(1)} GPA or higher`,
    weight,
  }),
  level: (levels: string[], weight: EligibilityRule['weight'] = 'required'): EligibilityRule => ({
    id: `level-${levels.join('-')}`,
    field: 'academics.level',
    operator: 'in',
    value: levels,
    label: `Open to ${levels.join(', ').replace(/-/g, ' ')} students`,
    weight,
  }),
  state: (states: string[]): EligibilityRule => ({
    id: `state-${states.join('-')}`,
    field: 'state',
    operator: 'in',
    value: states,
    label: `Resident of ${states.join(' or ')}`,
    weight: 'required',
  }),
  citizenship: (statuses: string[]): EligibilityRule => ({
    id: `citizenship-${statuses.join('-')}`,
    field: 'citizenship',
    operator: 'in',
    value: statuses,
    label: `${statuses.join(' or ').replace(/-/g, ' ')} status`,
    weight: 'required',
  }),
  major: (majors: string[], weight: EligibilityRule['weight'] = 'required'): EligibilityRule => ({
    id: `major-${majors.join('-')}`,
    field: 'academics.intendedMajors',
    operator: 'includes-any',
    value: majors,
    label: `Studying ${majors.join(', ')}`,
    weight,
  }),
  income: (max: number): EligibilityRule => ({
    id: `income-${max}`,
    field: 'financials.householdIncome',
    operator: 'lte',
    value: max,
    label: `Household income at or below $${max.toLocaleString()}`,
    weight: 'required',
  }),
  firstGen: (weight: EligibilityRule['weight'] = 'required'): EligibilityRule => ({
    id: 'first-gen',
    field: 'demographics.firstGeneration',
    operator: 'is-true',
    value: true,
    label: 'First-generation college student',
    weight,
  }),
  pell: (weight: EligibilityRule['weight'] = 'preferred'): EligibilityRule => ({
    id: 'pell',
    field: 'financials.pellEligible',
    operator: 'is-true',
    value: true,
    label: 'Pell Grant eligible',
    weight,
  }),
  fafsa: (): EligibilityRule => ({
    id: 'fafsa',
    field: 'financials.fafsaFiled',
    operator: 'is-true',
    value: true,
    label: 'FAFSA on file',
    weight: 'required',
  }),
  interests: (interests: string[], weight: EligibilityRule['weight'] = 'preferred'): EligibilityRule => ({
    id: `interest-${interests.join('-')}`,
    field: 'interests',
    operator: 'includes-any',
    value: interests,
    label: `Interest in ${interests.join(' or ')}`,
    weight,
  }),
  activities: (keywords: string[], weight: EligibilityRule['weight'] = 'preferred'): EligibilityRule => ({
    id: `activity-${keywords.join('-')}`,
    field: 'activities',
    operator: 'includes-any',
    value: keywords,
    label: `Involvement in ${keywords.join(' or ')}`,
    weight,
  }),
  sat: (min: number, weight: EligibilityRule['weight'] = 'preferred'): EligibilityRule => ({
    id: `sat-${min}`,
    field: 'academics.satTotal',
    operator: 'gte',
    value: min,
    label: `SAT ${min}+`,
    weight,
  }),
  ethnicity: (groups: string[]): EligibilityRule => ({
    id: `ethnicity-${groups.join('-')}`,
    field: 'demographics.ethnicities',
    operator: 'includes-any',
    value: groups,
    label: `Identifies as ${groups.join(' or ')}`,
    weight: 'required',
  }),
  military: (): EligibilityRule => ({
    id: 'military',
    field: 'demographics.militaryAffiliation',
    operator: 'exists',
    label: 'Military service member, veteran or dependent',
    weight: 'required',
  }),
  enrollment: (status: string): EligibilityRule => ({
    id: `enrollment-${status}`,
    field: 'academics.enrollment',
    operator: 'eq',
    value: status,
    label: `${status.replace(/-/g, ' ')} enrollment`,
    weight: 'required',
  }),
} as const;

interface SeedInput {
  id: string;
  name: string;
  sponsor: string;
  url: string;
  amountMin: number;
  amountMax: number;
  deadline: string;
  categories: ScholarshipCategory[];
  description: string;
  eligibility: EligibilityRule[];
  requirements: ApplicationRequirements;
  renewable?: boolean;
  renewableYears?: number;
  numberOfAwards?: number;
  estimatedApplicants?: number;
  states?: string[];
  tags?: string[];
}

function seed(input: SeedInput): Scholarship {
  return {
    renewable: false,
    states: [],
    tags: [],
    recurring: true,
    source: 'seed',
    ...input,
  };
}

